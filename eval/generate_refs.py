#!/usr/bin/env python3
"""
Generate reference extractions using baseline tools.

This is a ONE-TIME operation per PDF. The generated .md files are stored
alongside the PDFs and used for future comparisons.

Usage:
    python generate_refs.py --tool ours        # Generate using our Rust extraction
    python generate_refs.py --tool gemini      # Generate using Gemini API
    python generate_refs.py --tool markitdown  # Generate using MarkItDown
    python generate_refs.py --tool gemini --category legal  # Single category
    python generate_refs.py --tool gemini --force  # Regenerate all (overwrites existing)

File naming:
    document.pdf           → Source PDF
    document.ours.md       → Our Rust extraction (generated)
    document.gemini.md     → Gemini extraction (generated)
    document.markitdown.md → MarkItDown extraction (generated)
"""

import argparse
import sys
from pathlib import Path
from datetime import datetime

# Add parent to path for imports
EVAL_DIR = Path(__file__).parent
sys.path.insert(0, str(EVAL_DIR))

from tools.baselines import extract_with_tool, check_tool_available, AVAILABLE_TOOLS

CORPUS_DIR = EVAL_DIR / "corpus"
CATEGORIES = ["legal", "scientific", "financial", "scanned", "mixed"]


def get_ref_path(pdf_path: Path, tool: str) -> Path:
    """Get the reference file path for a PDF and tool."""
    return pdf_path.with_suffix(f".{tool}.md")


def generate_references(
    tool: str,
    categories: list[str] | None = None,
    force: bool = False,
    dry_run: bool = False
):
    """
    Generate reference extractions for all PDFs using specified tool.

    Args:
        tool: Extraction tool to use (gemini, markitdown, etc.)
        categories: List of categories to process (None = all)
        force: If True, regenerate even if reference exists
        dry_run: If True, just show what would be done
    """
    # Check tool availability
    available, status = check_tool_available(tool)
    if not available:
        print(f"Error: Tool '{tool}' not available: {status}")
        sys.exit(1)

    print(f"Generating references using: {tool}")
    print(f"Tool: {AVAILABLE_TOOLS.get(tool, 'Unknown')}")
    print("=" * 60)

    # Collect all PDFs
    all_pdfs = []
    for category in (categories or CATEGORIES):
        category_dir = CORPUS_DIR / category
        if not category_dir.exists():
            continue
        for pdf_path in sorted(category_dir.glob("*.pdf")):
            all_pdfs.append((category, pdf_path))

    if not all_pdfs:
        print("No PDF files found in corpus/")
        return

    # Process each PDF
    generated = 0
    skipped = 0
    failed = 0

    for category, pdf_path in all_pdfs:
        ref_path = get_ref_path(pdf_path, tool)

        # Check if already exists
        if ref_path.exists() and not force:
            print(f"  [{category}] {pdf_path.name} → SKIP (exists)")
            skipped += 1
            continue

        if dry_run:
            print(f"  [{category}] {pdf_path.name} → WOULD GENERATE")
            continue

        print(f"  [{category}] {pdf_path.name} → ", end="", flush=True)

        try:
            # Extract using tool
            markdown = extract_with_tool(tool, pdf_path)

            # Add metadata header
            header = f"""<!--
  Reference extraction generated by: {tool}
  Source: {pdf_path.name}
  Generated: {datetime.now().isoformat()}

  DO NOT EDIT - This file is auto-generated for benchmarking.
  To regenerate: python generate_refs.py --tool {tool} --force
-->

"""
            # Save reference file
            ref_path.write_text(header + markdown, encoding="utf-8")

            print(f"OK ({len(markdown):,} chars)")
            generated += 1

        except Exception as e:
            print(f"FAILED: {e}")
            failed += 1

    # Summary
    print()
    print("=" * 60)
    print(f"SUMMARY:")
    print(f"  Generated: {generated}")
    print(f"  Skipped (already exist): {skipped}")
    print(f"  Failed: {failed}")
    print(f"  Total PDFs: {len(all_pdfs)}")

    if generated > 0:
        print(f"\nReference files saved as: *.{tool}.md")


def list_status():
    """Show which PDFs have which reference files."""
    print("Reference file status:")
    print("=" * 60)

    tools = ["ours", "gemini", "markitdown", "claude"]

    for category in CATEGORIES:
        category_dir = CORPUS_DIR / category
        if not category_dir.exists():
            continue

        pdfs = list(category_dir.glob("*.pdf"))
        if not pdfs:
            continue

        print(f"\n[{category}]")

        for pdf_path in sorted(pdfs):
            refs = []
            for tool in tools:
                ref_path = get_ref_path(pdf_path, tool)
                if ref_path.exists():
                    refs.append(tool)

            ref_str = ", ".join(refs) if refs else "(none)"
            print(f"  {pdf_path.name}: {ref_str}")


def main():
    parser = argparse.ArgumentParser(
        description="Generate reference extractions using baseline tools"
    )
    parser.add_argument(
        "--tool", "-t",
        choices=["ours", "gemini", "markitdown", "claude"],
        help="Extraction tool to use"
    )
    parser.add_argument(
        "--category", "-c",
        choices=CATEGORIES,
        help="Process single category only"
    )
    parser.add_argument(
        "--force", "-f",
        action="store_true",
        help="Regenerate even if reference exists"
    )
    parser.add_argument(
        "--dry-run", "-n",
        action="store_true",
        help="Show what would be done without doing it"
    )
    parser.add_argument(
        "--status", "-s",
        action="store_true",
        help="Show which PDFs have which reference files"
    )

    args = parser.parse_args()

    if args.status:
        list_status()
        return

    if not args.tool:
        parser.print_help()
        print("\nExamples:")
        print("  python generate_refs.py --tool markitdown")
        print("  python generate_refs.py --tool gemini --category legal")
        print("  python generate_refs.py --status")
        return

    categories = [args.category] if args.category else None
    generate_references(
        tool=args.tool,
        categories=categories,
        force=args.force,
        dry_run=args.dry_run
    )


if __name__ == "__main__":
    main()
